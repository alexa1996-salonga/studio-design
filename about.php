<h1>THE HISTORY OF CALGARY’S +15 SKYWALK</h1>
<h2>TAKE A WALK THROUGH THIS PAGE TO LEARN MORE BOUT THE +15</h2>

        <h3>What is the +15 Skywalk?</h3>
        <p>The Calgary +15 skywalk is a bridging system that runs throughout downtown Calgary connecting most buildings to one another for easy access. It allows for easy accessibility for all ages and abilities, connecting people throughout certain buildings in downtown whether it be food courts, shopping centres, public art, or even office and work related buildings. The skywalk comprises 86 bridge connections that are situated 15 feet above the street levels, hence the name “+15”.</p>

        <img src="https://placehold.co/600x400" alt="Placeholder image">

        <p>With the winter season coming round the corner, the +15 skywalk was built to keep citizens warm and protected from the cold and snowy weather outside.The skywalk keeps the pedestrians far away from the bustling streets of cars and buses as the bridges themselves are situated pretty high up.</p>

        <p>The +15 skywalk is its own historical hidden gem within Calgary downtown as quite a lot of people still are not aware of its existence (or its name).</p>

        <h3>How and when was it built?</h3>
        <p>The first ever Calgary +15 skywalk was built in 1969 which is almost 30 decades old! It was built by Harold Hanen. This bridge connected what used to be the Calgary Inn- now The Westin- to the Calgary place. Not only was Harold Helen the person who developed the first Calgary skywalk bridge but also the one who developed the concept and design of the bridges along with a few others for help.</p>



        <h3>Why it was built</h3>
        <p>Due to the increasing population within Calgary and downtown, the skywalk was built to decrease foot traffic by giving another passage for citizens to walk through. It helps with traffic flow, density in downtown, as well as protection from the harsh weather in winter.</p>

        <img src="https://placehold.co/600x400" alt="Placeholder image">


        <h3>Why people use it</h3>
        <p>Based on the 2019 survey, people use the Plus 15 network not only to avoid poor weather but also because it offers convenient routes, easier street crossings, access to shops and restaurants, and connections to workplaces. Many users enter the network through office buildings, highlighting the important role that downtown office towers play as key access points and destinations.</p>

        <p>The survey also found that users regularly take advantage of the amenity spaces throughout the network, including seating areas, gardens, and open spaces. This suggests that these public spaces are valued and contribute positively to the overall user experience within the Plus 15 network.</p>

        <p>The most sought-after destinations accessible through the Plus 15 network are LRT stations, office buildings, and commercial spaces. These destinations represent the primary reasons users rely on the network, emphasizing its role in supporting daily commuting, work-related travel, and access to services.</p>



